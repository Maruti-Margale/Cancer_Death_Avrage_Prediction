import pandas as pd

from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error,r2_score
from sklearn.preprocessing import MinMaxScaler

df = pd.read_csv("/content/cancer_reg.csv")
df

df.info()

df.columns

df = df[['avganncount','avgdeathsperyear', 'target_deathrate', 'incidencerate',
       'medincome', 'popest2015', 'povertypercent', 'studypercap',
       'medianage', 'medianagemale', 'medianagefemale',
       'percentmarried', 'pctnohs18_24', 'pcths18_24',
       'pctbachdeg18_24', 'pcths25_over', 'pctbachdeg25_over',
       'pctemployed16_over', 'pctunemployed16_over', 'pctprivatecoverage',
      'pctempprivcoverage', 'pctpubliccoverage',
       'pctpubliccoveragealone', 'pctwhite', 'pctblack', 'pctasian',
       'pctotherrace', 'pctmarriedhouseholds', 'birthrate']]

df.dropna(inplace=True)

df.info()

y = df['avganncount']

df = df[['avgdeathsperyear', 'target_deathrate', 'incidencerate',
       'medincome', 'popest2015', 'povertypercent', 'studypercap',
       'medianage', 'medianagemale', 'medianagefemale',
       'percentmarried', 'pctnohs18_24', 'pcths18_24',
       'pctbachdeg18_24', 'pcths25_over', 'pctbachdeg25_over',
       'pctemployed16_over', 'pctunemployed16_over', 'pctprivatecoverage',
      'pctempprivcoverage', 'pctpubliccoverage',
       'pctpubliccoveragealone', 'pctwhite', 'pctblack', 'pctasian',
       'pctotherrace', 'pctmarriedhouseholds', 'birthrate']]

scaler = MinMaxScaler()
df[df.columns] = scaler.fit_transform(df[df.columns])

df

x = df[df.columns]

x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.20,random_state=12)

model = LinearRegression()

model.fit(x_train,y_train)

pred = model.predict(x_test)

print(r2_score(y_test,pred))

print(mean_squared_error(y_test,pred))

import pickle

with open("Cancer_Regression.pkl",'wb') as file:
  pickle.dump(model,file)

